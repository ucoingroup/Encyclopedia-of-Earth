window.addEventListener('scroll', function() {
  var sections = ['hero','about','dimensions','ecosystem','community','dex'];
  var scrollPos = window.scrollY + 100;
  for (var i = sections.length - 1; i >= 0; i--) {
    var el = document.getElementById(sections[i]);
    if (el && el.offsetTop <= scrollPos) {
      document.querySelectorAll('nav a[data-section]').forEach(function(a) { a.classList.remove('active'); });
      var navMap = {'hero':'nav-home','about':'nav-about','dimensions':'nav-dim','ecosystem':'nav-eco','community':'nav-com','dex':'nav-dex'};
      var navId = navMap[sections[i]];
      if (navId) document.getElementById(navId)?.classList.add('active');
      break;
    }
  }
});

